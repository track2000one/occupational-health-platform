export type NationalityOption = {
  code: string;
  countryAr: string;
  countryEn: string;
  nationalityAr: string;
  searchText: string;
};

export function normalizeNationalitySearch(value: string): string {
  return value.toLocaleLowerCase().normalize('NFKD')
    .replace(/[\u064B-\u065F]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/\s+/g, ' ').trim();
}

export function getNationalityOptions(): NationalityOption[] {
  const arNames = new Intl.DisplayNames(['ar'], { type: 'region' });
  const enNames = new Intl.DisplayNames(['en'], { type: 'region' });
  const seen = new Set(ARAB_COUNTRY_CODES);
  const ordered = [...ARAB_COUNTRY_CODES,
    ...WORLD_COUNTRY_CODES.filter(code => !seen.has(code)).sort((a,b) =>
      (arNames.of(a) || a).localeCompare(arNames.of(b) || b, 'ar'))];
  return ordered.map(code => {
    const countryAr = ARAB_COUNTRY_SHORT_NAMES[code] || arNames.of(code) || code;
    const countryEn = enNames.of(code) || code;
    const nationalityAr = ARAB_NATIONALITY_NAMES[code] || '';
    return {
      code, countryAr, countryEn, nationalityAr,
      searchText: normalizeNationalitySearch([countryAr, arNames.of(code) || '', countryEn, nationalityAr, code].join(' ')),
    };
  });
}
